## القسم الأول: خمسة أسئلة استماع محلولة

**١. اختيار الصورة المناسبة**

> 가: 이거 얼마예요? 나: 오천 원이에요.

السؤال: ما الذي يدور حوله الحوار؟
**الإجابة: سعر شيء في محل.** الشرح: 얼마예요 تعني "بكم هذا؟"، والرد يذكر رقمًا بالوون (오천 원 = خمسة آلاف وون)، وهذا نمط سؤال السعر المتكرر في الأسئلة 1-4 من قسم الاستماع.

**٢. إكمال الحوار المناسب**

> 가: 어디에서 친구를 만나요?

**الإجابة الصحيحة: 나: 학교 앞에서 만나요. (نلتقي أمام المدرسة)**
الشرح: السؤال بدأ بكلمة الاستفهام **어디 (أين)**، فالإجابة الصحيحة يجب أن تكون مكانًا، لا وقتًا ولا شخصًا. أي إجابة تذكر زمنًا مثل "지금 만나요" تكون خاطئة رغم أنها جملة صحيحة نحويًا.

**٣. فهم حوار قصير والإجابة عن سؤال تفصيلي**

> 가: 주말에 보통 뭐 해요? 나: 저는 보통 집에서 쉬어요. 가끔 영화를 봐요.

السؤال: ماذا تفعل "나" عادة في عطلة نهاية الأسبوع؟
**الإجابة: ترتاح في البيت، وأحيانًا تشاهد فيلمًا.**
الشرح: كلمة **보통** تعني "عادة" وتدل على الفعل المعتاد (الراحة في البيت)، بينما **가끔** تعني "أحيانًا" وتدل على الفعل الأقل تكرارًا (مشاهدة فيلم). الخطأ الشائع هو عكس الترتيب بين الفعلين.

**٤. تحديد المكان من سياق الحوار**

> 가: 여기 책이 얼마예요? 나: 만 원이에요. 가: 두 권 주세요.

السؤال: أين يدور هذا الحوار على الأرجح؟
**الإجابة: في مكتبة (서점).**
الشرح: كلمة **책 (كتاب)** و**권** (عدّاد الكتب/المجلدات) تحدد المكان بوضوح، رغم أن كلمة "مكتبة" لم تُذكر مباشرة. هذا النوع يختبر الاستدلال من المفردات لا الفهم الحرفي فقط.

**٥. فهم الفكرة العامة لحوار أطول**

> 가: 요즘 한국어 공부가 어때요? 나: 처음에는 어려웠는데, 요즘은 재미있어요. 매일 30분씩 공부해요.

السؤال: ما شعور "나" تجاه دراسة الكورية الآن؟
**الإجابة: أصبحت ممتعة بعد أن كانت صعبة في البداية.**
الشرح: الجملة الرابطة **-는데** هنا تفيد التضاد (كانت صعبة، لكنها الآن ممتعة). الفخ الشائع هو التوقف عند "처음에는 어려웠는데" (كانت صعبة) واختيار إجابة سلبية، متجاهلين الجزء الذي يأتي بعد الرابط وهو الأهم غالبًا في نمط الأسئلة.

## القسم الثاني: خمسة أسئلة قراءة محلولة

**٦. ملء الفراغ بأداة الربط المناسبة**

> 오늘은 바빠요. ( ) 내일은 시간이 있어요.

اختاري المناسب: 그리고 / 그래서 / 하지만

**الإجابة: 하지만 (لكن).**
الشرح: الجملتان متضادتان (مشغولة اليوم ≠ لديها وقت غدًا)، وأداة التضاد الوحيدة بين الخيارات الثلاثة هي **하지만**. **그리고** تضيف فكرة متوافقة، و**그래서** تربط سببًا بنتيجة، وكلاهما غير مناسب هنا.

**٧. اختيار الموضوع العام لنص قصير**

> 저는 매일 아침 7시에 일어나요. 간단하게 아침을 먹고 학교에 가요. 수업은 9시에 시작해요.

السؤال: ما موضوع النص؟
**الإجابة: الروتين اليومي الصباحي للكاتب.**
الشرح: كل جملة في النص تصف خطوة زمنية متتالية (7:00 الاستيقاظ، ثم الفطور، ثم 9:00 بدء الدروس)؛ هذا التتابع الزمني هو العلامة المميزة لنصوص "الروتين اليومي" في قسم القراءة.

**٨. ربط جملتين بأداة السبب والنتيجة**

> 날씨가 추워요. ( ) 따뜻한 옷을 입어요.

**الإجابة: 그래서 (لذلك).**
الشرح: الجملة الأولى سبب (الجو بارد)، والثانية نتيجة طبيعية له (ارتداء ملابس دافئة). **그래서** هي أداة الربط التي تفيد "السبب ← النتيجة"، وهي من أكثر خمس أدوات ربط تكرارًا في TOPIK I.

**٩. فهم إعلان أو لافتة قصيرة**

> 이 가게는 월요일에 쉽니다.

السؤال: ماذا يعني هذا الإعلان؟
**الإجابة: المحل مغلق يوم الاثنين.**
الشرح: الفعل **쉬다** هنا بمعنى "يأخذ إجازة/يُغلق"، لا "يستريح" بالمعنى الحرفي فقط. هذا النوع من الأسئلة (لافتات، إعلانات، جداول) يتكرر بثبات في الأسئلة 9-12 من قسم القراءة.

**١٠. تحديد الفكرة الرئيسية لفقرة قصيرة**

> 저는 한국 음식을 좋아해요. 특히 김치찌개를 자주 먹어요. 하지만 매운 음식은 조금만 먹을 수 있어요.

السؤال: ما الفكرة الرئيسية؟
**الإجابة: الكاتب يحب الطعام الكوري لكن قدرته على تحمّل الحار محدودة.**
الشرح: الفخ هنا هو التوقف عند الجملتين الأوليين (يحب الطعام الكوري، يأكل الكيمتشي جيغاي كثيرًا) واختيار إجابة تتجاهل **하지만** في الجملة الأخيرة، التي تقيّد الفكرة السابقة. في فقرات TOPIK I القصيرة، الجملة الأخيرة غالبًا ما تحمل التفصيل الذي يفرّق بين إجابتين متشابهتين.

