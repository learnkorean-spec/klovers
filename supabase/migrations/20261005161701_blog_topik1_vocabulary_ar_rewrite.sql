اختبار TOPIK (اختبار الكفاءة في اللغة الكورية) هو الاختبار الرسمي للغة الكورية، وتعترف به الحكومة الكورية والجامعات وجهات العمل حول العالم، فهو المقابل الكوري لاختبارَي IELTS وTOEFL.

**اختبار TOPIK I** هو اختبار المبتدئين، ويغطي المستويين ١ و٢. يحتاج النجاح في المستوى ١ إلى نحو ٨٠٠ كلمة، ويحتاج المستوى ٢ إلى ما بين ١٥٠٠ و٢٠٠٠ كلمة تقريبًا.

يعرض هذا الدليل الفئات الأساسية للمفردات، وأهم الكلمات في كل فئة، وخطة دراسة للوصول إلى TOPIK I. النطق مكتوب بحروف عربية تقريبية، والأفضل دائمًا سماع الكلمة من مصدر صوتي.

