## خطة مفردات في ثلاثة أشهر

**الشهر الأول:** إتقان الهانغول، ثم الفئات من ١ إلى ٣ (نحو ١٠٠ كلمة).
**الشهر الثاني:** الفئات من ٤ إلى ٧، مع أساسيات القواعد (نحو ٢٠٠ كلمة إضافية).
**الشهر الثالث:** الفئات من ٨ إلى ١٠، ثم نماذج اختبارات TOPIK السابقة مع مراجعة كل الكلمات.

تساعد بطاقات المراجعة المتباعدة، مثل تطبيق Anki، على تثبيت الكلمات. ووضع كل كلمة في جملة واحدة على الأقل يجعلها أسهل في التذكر. والنماذج السابقة لاختبار TOPIK منشورة مجانًا على الموقع الرسمي، والأفضل حلّها بالتوقيت الحقيقي.

## المفردات وحدها لا تكفي

لا يكفي حفظ المفردات وحده لاجتياز TOPIK I، فالاختبار يقيس أيضًا:
- فهم المقروء (القواعد في سياقها)
- فهم المسموع (سرعة الكلام واختلاف النطق)

وأسرع طريق هو منهج منظم يطوّر المهارات معًا. في كلوفرز، يتوافق منهج المستوى الأول مع معايير TOPIK I، ويجمع المفردات والقواعد واستراتيجيات الاختبار في حصص مباشرة أسبوعية.

